def is_version(value: str) -> bool:
    """Whether a tag spells a version. "^" is out: the rendering appends it as a separator."""
    return bool(value) and all(c.isascii() and (c.isalnum() or c in "._~-") for c in value)


def buckconfig_value_round_trips(value: str) -> bool:
    """Return whether buckconfig preserves a value.

    A trailing backslash swallows the next line, a newline splits one entry in two, and space around a
    value is stripped.
    """
    return value == value.strip() and not value.endswith("\\") and "\n" not in value


def is_hex(value: str, length: int) -> bool:
    return len(value) == length and all(c in "0123456789abcdef" for c in value)


def cwd() -> Path:
    try:
        return Path.cwd()
    except OSError as error:
        fail(f"cannot read the working directory: {error}")


def project_root(start: Path) -> Path:
    """The furthest ancestor holding a .buckconfig, the same root Buck itself resolves to."""
    root = None
    # The only home directory Buck knows: it never falls back to the password database.
    home = os.environ.get("HOME")
    for directory in [start, *start.parents]:
        if (directory / ".buckconfig").is_file():
            # `~/.buckconfig` configures every project, so Buck stops rather than taking the home
            # directory for one.
            if home and directory == Path(home):
                break
            root = directory
        if (directory / ".buckroot").is_file():
            break
    if root is None:
        fail(f"no .buckconfig in {start} or any parent directory")
    return root


def ensure_home(root: Path) -> None:
    """A home directory to stand in for the one the environment does not set.

    Buck2, git, the tools a build runs and any nested Buck2 all read it and all have to agree.
    """
    if os.environ.get("HOME"):
        return
    path = (root / HOME).absolute()
    try:
        path.mkdir(exist_ok=True)
    except OSError as error:
        fail(f"cannot create {path} to use as a home directory: {error}")
    os.environ["HOME"] = str(path)


def section_marker(line: str) -> str | None:
    """The section a line opens, or None. Buck2 accepts a trailing comment on a marker."""
    marker = line.strip().split(" #", 1)[0].rstrip()
    return marker[1:-1] if marker.startswith("[") and marker.endswith("]") else None


def read_lines(path: Path) -> list[str]:
    """Read a file using Buck2's line semantics.

    Buck2 splits only at LF characters. `str.splitlines` also splits on form feeds and several other
    characters, while `read_text` turns a stray carriage return into a newline. Either behavior could
    rewrite a line Buck cannot read.
    """
    try:
        text = path.read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError) as error:
        fail(f"cannot read {path}: {error}")
    lines = text.split("\n")
    return lines[:-1] if not lines[-1] else lines


def read_toml(path: Path) -> dict[str, object]:
    """Read a TOML file, treating an absent one as empty configuration."""
    try:
        with path.open("rb") as handle:
            return cast(dict[str, object], tomllib.load(handle))
    except FileNotFoundError:
        return {}
    except tomllib.TOMLDecodeError as error:
        fail(f"cannot parse {path}: {error}")
    except (OSError, UnicodeDecodeError) as error:
        fail(f"cannot read {path}: {error}")


def project_settings(root: Path) -> dict[str, dict[str, object]]:
    """Read the settings understood by Tine rather than Buck.

    LOCAL_SETTINGS merges into CONFIG for individual keys: setting one in local still leaves the rest of
    that section in CONFIG active.
    """
    merged: dict[str, dict[str, object]] = {}
    for path in (root / CONFIG, root / LOCAL_SETTINGS):
        settings = read_toml(path)
        if extra := sorted(set(settings) - {BUCK2, COMMANDS, BUCKCONFIG}):
            fail(f"{path} has unknown sections: {', '.join(extra)}")
        for section, table in settings.items():
            merged[section] = merged.get(section, {}) | object_table(table, f"[{section}] in {path}")
    return merged


def _split_generated_block(path: Path, *, must_exist: bool = False) -> tuple[list[str], list[str]]:
    """What a file holds besides the block this writes into it, and what that block holds.

    Keeping the generated block separate prevents a later command from treating generated values as
    project configuration. Reject partial blocks because later buckconfig entries take precedence.
    """
    if not must_exist and not path.is_file():
        return [], []
    kept: list[str] = []
    generated: list[str] = []
    inside = False
    for line in read_lines(path):
        if line.strip() == BLOCK_BEGIN:
            if inside:
                fail(f"{path}: a generated block begins inside another; restore or delete it")
            inside = True
        elif line.strip() == BLOCK_END:
            if not inside:
                fail(f"{path}: a generated block ends without beginning; restore or delete it")
            inside = False
        else:
            (generated if inside else kept).append(line)
    if inside:
        fail(f"{path}: the generated block has no {BLOCK_END!r} line; restore or delete it")
    return kept, generated


def _logical_buckconfig_lines(lines: list[str]) -> list[str]:
    """Buckconfig lines as entries: continuations joined, comments and blanks dropped."""
    logical: list[str] = []
    # Buck2 continues a comment too, and what follows one belongs to it, not to the entry before.
    kept = continued = False
    for raw in lines:
        line = raw.strip()
        if continued:
            continued = line.endswith("\\")
            if kept:
                logical[-1] = logical[-1][:-1] + line
            continue
        kept = bool(line) and not line.startswith(("#", ";"))
        if kept:
            logical.append(line)
        continued = line.endswith("\\")
    return logical


def parse_buckconfig(
    path: Path, config: dict[str, dict[str, str]] | None = None
) -> dict[str, dict[str, str]]:
    """A buckconfig file's sections, following the includes Buck2 would follow."""
    config = {} if config is None else config
    _parse_buckconfig_file(path, config, "")
    return config


def _parse_buckconfig_file(path: Path, config: dict[str, dict[str, str]], section: str) -> str:
    """A file read into the section it was reached from, reporting back the one it ends in.

    Buck2 continues an include wherever the included file left off.
    """
    if not path.is_file():
        return section

    config.setdefault(section, {})
    return _parse_buckconfig_lines(
        _logical_buckconfig_lines(_split_generated_block(path)[0]), config, section, path.parent
    )


def _parse_buckconfig_lines(
    lines: list[str], config: dict[str, dict[str, str]], section: str, directory: Path
) -> str:
    for line in lines:
        if line.startswith("["):
            if (marker := section_marker(line)) is not None:
                section = marker
                config.setdefault(section, {})
        elif line.startswith("<") and ">" in line:
            # `<file:path>`, or `<?file:path>` where it need not exist; Buck2 ignores the rest.
            include = line[1 : line.index(">")].removeprefix("?")
            if include.startswith("file:"):
                section = _parse_buckconfig_file(directory / include.removeprefix("file:"), config, section)
        elif "=" in line:
            key, _, value = line.partition("=")
            if key.strip():
                config.setdefault(section, {})[key.strip()] = value.strip()
    return section


def read_generated_buckconfig(path: Path) -> dict[str, dict[str, str]]:
    """What the block this owns says, as against what the project configures for itself."""
    config: dict[str, dict[str, str]] = {}
    _parse_buckconfig_lines(
        _logical_buckconfig_lines(_split_generated_block(path)[1]), config, "", path.parent
    )
    return config


def read_project_buckconfig(
    root: Path, overrides: dict[str, dict[str, str]] | None = None
) -> dict[str, dict[str, str]]:
    """Read the root cell's project-owned layered configuration.

    Buck2 loads all of `.buckconfig.d` in name order, followed by `.buckconfig` and then
    `.buckconfig.local`. Apply pending TOML overrides at the root file's precedence for cell selection
    before a refresh. Exclude generated blocks so they are not mistaken for project-owned settings.
    """
    config: dict[str, dict[str, str]] = {}
    # Buck lists entries with lstat and does not load symlinked files.
    paths = [path for path in sorted((root / ".buckconfig.d").rglob("*")) if not path.is_symlink()]
    for path in [*paths, root / ".buckconfig", root / LOCAL]:
        parse_buckconfig(path, config)
        if path == root / ".buckconfig" and overrides is not None:
            for section, values in overrides.items():
                config.setdefault(section, {}).update(values)
    return config


def resolve_mount_target(argument: Path) -> Path:
    """Resolve a mount target's parent while preserving its final component.

    This keeps a target removable if its final component later becomes a symlink.
    `validate_mount_declaration` rejects symlink targets before mounting them.
    """
    path = argument.expanduser()
    return resolved(path.parent) / path.name


def relative_mount_target(root: Path, path: Path) -> str:
    try:
        target = path.relative_to(root)
    except ValueError:
        fail(f"{path} is outside the project at {root}")
    if target == Path():
        fail(f"{root} is the project root and cannot be mounted over")
    return target.as_posix()


def string_table(value: object, description: str) -> dict[str, str]:
    """Require a TOML table whose values are strings."""
    table: dict[str, str] = {}
    for key, item in object_table(value, description).items():
        if not isinstance(item, str):
            fail(f"{description} must contain only strings")
        table[key] = item
    return table


def local_mounts(root: Path) -> dict[str, str]:
    """Read the machine-local mount table owned by `tine mount`."""
    path = root / MOUNT_CONFIG
    config = read_toml(path)
    if extra := sorted(set(config) - {MOUNTS}):
        fail(f"{path} is owned by `tine mount` and has unsupported keys: {', '.join(extra)}")
    return string_table(config.get(MOUNTS, {}), f"[{MOUNTS}] in {path}")


def render_mounts(mounts: dict[str, str]) -> str:
    """Serialize the local mount table as TOML."""
    import json

    lines = ["# @generated by `tine mount`; edit mounts with that command, not by hand."]
    if mounts:
        lines += ["", f"[{MOUNTS}]"]
        # JSON strings are TOML basic strings too, including the escaping paths need here.
        lines += [
            f"{json.dumps(target, ensure_ascii=False)} = {json.dumps(source, ensure_ascii=False)}"
            for target, source in sorted(mounts.items())
        ]
    return "\n".join(lines) + "\n"


def write_mounts(root: Path, mounts: dict[str, str]) -> None:
    """Atomically replace the machine-local mount configuration."""
    path = root / MOUNT_CONFIG
    path.parent.mkdir(parents=True, exist_ok=True)
    write_if_changed(path, render_mounts(mounts))


def validate_mount_declaration(
    root: Path,
    target: str,
    source: str,
    *,
    declared: bool = False,
    allow_missing_target: bool = False,
) -> None:
    """Validate a mount declaration.

    A graph-declared checkout slot is validated before `add` creates its mount-point directory.
    """
    drop = f"; `tine mount remove {target}` drops it" if declared else ""
    path = Path(target)
    if path.is_absolute() or ".." in path.parts or path == Path():
        fail(f"mount {target}: target must be a project-relative path")
    for reserved in (HOME, ".buckconfig.d"):
        if path.is_relative_to(reserved):
            fail(f"mount {target}: {reserved} is reserved for tine")
    # mount table goes into a config value, ensure names don't break that
    if any(c.isspace() or c == "," for c in target):
        fail(f"mount {target}: target must not contain whitespace or commas")
    if not Path(source).is_absolute():
        fail(f"mount {target}: source must be an absolute path, got {source}")
    if not (root / target).is_dir() and not (allow_missing_target and not (root / target).exists()):
        fail(f"mount {target}: this project has no such directory{drop}")
    if resolved(root / target) != root / target:
        fail(f"mount {target}: target is a symlink{drop}")
    if not Path(source).is_dir():
        fail(f"mount {target}: {source} is not a directory{drop}")
    if resolved(Path(source)).is_relative_to(root):
        fail(f"mount {target}: source {source} must be outside the project{drop}")


def mount_targets_overlap(first: str, second: str) -> bool:
    return Path(first).is_relative_to(second) or Path(second).is_relative_to(first)


def declared_mounts(root: Path) -> dict[str, str]:
    """Read and validate the mount declarations for a project.

    Invalid declarations stop the command instead of silently falling back to checked-in contents.
    Overlapping mounts are rejected because an outer mount can hide an inner target.
    """
    mounts: dict[str, str] = {}
    for target, source in sorted(local_mounts(root).items()):
        validate_mount_declaration(root, target, source, declared=True)
        for other in mounts:
            if mount_targets_overlap(target, other):
                fail(f"mount {target}: overlaps mount {other}")
        mounts[target] = source
    return mounts


def mount_digest(root: Path, mounts: dict[str, str]) -> str:
    """Identify the mounts a daemon inherited, including replaced source directories.

    After mounting, read the target inode: the source path may already name a replacement directory.
    Omit the device because btrfs can assign a new one each time a subvolume is mounted.
    """
    import hashlib

    digest = hashlib.sha256()
    for target, source in sorted(mounts.items()):
        try:
            info = (root / target).stat()
        except OSError as error:
            fail(f"mount {target}: cannot read {root / target}: {error}")
        digest.update(f"{target}\0{source}\0{info.st_ino}\0".encode())
    return digest.hexdigest()[:16]


def _git_bytes(*args: str, directory: Path) -> bytes:
    import subprocess

    environment = {k: v for k, v in os.environ.items() if k not in GIT_LOCATION_VARS}
    command = ["git", "-C", str(directory), *args]
    try:
        proc = subprocess.run(command, capture_output=True, env=environment)
    except OSError:
        fail("required tool not found: git")
    if proc.returncode != 0:
        # One line: a reason ends up in a generated buckconfig, where anything after the first line
        # would be read as configuration.
        reason = " ".join(proc.stderr.decode(errors="replace").split()) or f"exit {proc.returncode}"
        fail(f"git {' '.join(args)}: {reason}")
    return proc.stdout


def _git(*args: str, directory: Path) -> str:
    try:
        return _git_bytes(*args, directory=directory).decode().strip()
    except UnicodeDecodeError as error:
        fail(f"git {' '.join(args)} returned non-UTF-8 output: {error}")


def git_ignored_paths(
    directory: Path, *, gitdir: str | None = None, excludes: tuple[str, ...] = ()
) -> list[str]:
    """Return minimal untracked roots matched by checkout-local Git ignores."""
    if not (directory / ".git").exists():
        return []

    output = _git_bytes(
        # A submodule's core.worktree can still name its original, now replaced checkout.
        *([f"--git-dir={gitdir}", "--work-tree=."] if gitdir is not None else []),
        # Include info/exclude with Git's normal precedence, but not machine-wide ignore files.
        "-c",
        "core.excludesFile=/dev/null",
        "ls-files",
        "--others",
        "--ignored",
        "--directory",
        "--exclude-standard",
        *(f"--exclude={pattern}" for pattern in excludes),
        "-z",
        "--",
        directory=directory,
    )
    try:
        paths = output.decode().split("\0")
    except UnicodeDecodeError as error:
        fail(f"gitignored path in {directory} is not UTF-8: {error}")

    ignored = []
    for value in paths:
        value = value.removesuffix("/")
        if not value:
            continue
        path = Path(value)
        if path.is_absolute() or ".." in path.parts:
            fail(f"git returned an invalid ignored path for {directory}: {value!r}")
        if "," in value or not buckconfig_value_round_trips(value):
            fail(f"gitignored path cannot be represented in Buck project.ignore: {value!r}")
        ignored.append(value)
    paths = set(ignored)
    return sorted(
        value
        for value in paths
        if not any(parent != Path() and parent.as_posix() in paths for parent in Path(value).parents)
    )


def version_components(root: Path) -> dict[str, object] | str:
    """What a version is derived from, keyed as the configuration spells it, or why there is none.

    `height` is what a version no tag named a base for counts its distance in, a new tag resetting
    `count` and ordering that build below the one before it. The reason is recorded, not raised: a
    checkout git cannot answer for still has to run every command that needs no version.
    """
    if not (root / ".git").exists():
        return "not a git checkout"
    try:
        # Truncated history answers `describe` and `rev-list --count` confidently and wrongly.
        if _git("rev-parse", "--is-shallow-repository", directory=root) == "true":
            return "shallow git checkout"
        head = _git("rev-parse", "HEAD", directory=root)
        height = int(_git("rev-list", "--count", "HEAD", directory=root))
        # `v[0-9]*` rather than `v*`, which matches `vendor-2024` and reads it as `endor-2024`.
        # `--always` falls back to the bare commit hash, which the 0.0.0 base below stands in for.
        # The nearest tag, not the highest, so a merge of a lower-tagged branch moves the base back.
        described = _git(
            "describe", "--tags", "--match", "v[0-9]*", "--abbrev=0", "--always", directory=root
        )
        if described.startswith("v"):
            base = described.removeprefix("v")
            # Qualified, or a branch sharing the tag's name makes the revision ambiguous.
            count = int(_git("rev-list", "--count", f"refs/tags/{described}..HEAD", directory=root))
        else:
            base = "0.0.0"
            count = height
        if not is_version(base):
            return f"tag {described!r} is not a valid version"

        # -unormal, or `status.showUntrackedFiles=no` in the caller's configuration would present a
        # tree carrying uncommitted work as a clean checkout.
        dirty = bool(_git("status", "--porcelain", "-unormal", directory=root))
    except SystemExit as error:
        return str(error).removeprefix("tine: ")
    derived: dict[str, object] = {"base": base, "count": count, "height": height, "commit": head}
    if dirty:
        derived["dirty"] = 1
    return derived


def render_local_config_block(root: Path, ignores: list[str]) -> list[str]:
    lines = [BLOCK_BEGIN, BLOCK_NOTE]
    derived = version_components(root)
    if isinstance(derived, str):
        lines.append(f"# no version components: {derived}")
    else:
        lines += ["", f"[{SECTION}]"] + [f"version-{key} = {value}" for key, value in derived.items()]
    if ignores:
        # A file rather than `--config`: the daemon's file watcher takes its ignores from the
        # configuration files at startup, where an override never reaches, and a single argument
        # cannot exceed 128 KiB.
        entries = [f"{entry}, \\" for entry in ignores[:-1]] + [ignores[-1]]
        lines += ["", "[project]", f"{PROJECT_IGNORE} = {entries[0]}"]
        lines += [f"    {entry}" for entry in entries[1:]]
    return lines + [BLOCK_END]


def merge_generated_config_block(path: Path, block: list[str]) -> str:
    kept = _split_generated_block(path)[0]
    while kept and not kept[0].strip():
        kept.pop(0)
    return "\n".join(block + ([""] + kept if kept else [])) + "\n"


def refresh_local_buckconfig(root: Path, ignores: list[str]) -> None:
    """Refresh the version data and mount ignores Buck consumes from its local configuration."""
    local = root / LOCAL
    write_if_changed(local, merge_generated_config_block(local, render_local_config_block(root, ignores)))


def _host_platform() -> str:
    system, _, _, _, machine = os.uname()
    if (platform := f"{system}-{machine}") not in PLATFORMS:
        fail(f"unsupported platform: {platform}")
    return platform


def _decompress_zstd(archive: Path, binary: Path) -> None:
    """Unpack a zstd-compressed release artifact, without `zstd` where python can do it itself."""
    if sys.version_info < (3, 14):
        _unzstd(archive, binary)
        return
    try:
        from compression import zstd
    except ImportError:
        _unzstd(archive, binary)
        return
    try:
        with zstd.open(archive) as compressed, binary.open("wb") as out:
            while chunk := compressed.read(1 << 20):
                out.write(chunk)
    except (zstd.ZstdError, EOFError) as error:
        fail(f"the pinned artifact is not a whole zstd stream: {error}")


def _unzstd(archive: Path, binary: Path) -> None:
    """The `zstd` command, for a python whose standard library cannot unpack one itself."""
    import subprocess

    command = ["zstd", "--decompress", "--force", "--quiet", str(archive), "-o", str(binary)]
    try:
        proc = subprocess.run(command)
    except OSError:
        fail("required tool not found: zstd, or a python 3.14 or newer to unpack with")
    if proc.returncode != 0:
        fail(f"zstd could not unpack {archive}")


def _download_binary(url: str, sha256: str, binary: Path, *, compressed: bool) -> Path:
    import hashlib
    import tempfile
    import urllib.request

    into = binary.parent
    print(f"tine: downloading {url}", file=sys.stderr)
    digest = hashlib.sha256()
    try:
        # Beside the cache entry rather than inside it, so a download that does not verify leaves
        # nothing behind and the rename below stays on one filesystem.
        into.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(dir=into.parent, prefix=".download.") as directory:
            fetched = Path(directory) / ".fetched"
            with urllib.request.urlopen(url, timeout=120) as response, fetched.open("wb") as out:
                while chunk := response.read(1 << 20):
                    digest.update(chunk)
                    out.write(chunk)
            if digest.hexdigest() != sha256:
                fail(f"{url} has SHA-256 {digest.hexdigest()}, not the pinned {sha256}")
            unpacked = Path(directory) / binary.name
            if compressed:
                _decompress_zstd(fetched, unpacked)
            else:
                fetched.replace(unpacked)
            unpacked.chmod(0o755)
            into.mkdir(exist_ok=True)
            unpacked.replace(binary)
    except OSError as error:
        fail(f"cannot fetch {url}: {error}")
    return binary


def wrapper_cell_root() -> Path:
    """The checkout this command is part of, which is the cell whose rules a project builds.

    Resolved, since putting the command on `PATH` means a symlink to it.
    """
    return COMMAND_PATH.resolve().parent.parent


def declared_pin(cell: Path, tool: str, platform: str) -> dict[str, str]:
    """The pin a cell declares for one tool on this machine."""
    import json

    path = cell / PINS
    try:
        spec = json.loads(path.read_text(encoding="utf-8"))[tool]
        entry = spec["platforms"][platform]
        return {
            "repository": spec["repository"],
            "release": spec["release"],
            "artifact": entry["artifact"],
            "sha256": entry["sha256"],
        }
    except OSError as error:
        fail(f"cannot read {path}: {error}")
    except (KeyError, TypeError, ValueError) as error:
        fail(f"{path} declares no {tool} for {platform}: {error}")


def buck2_pin_overrides(config: Mapping[str, object], platform: str) -> dict[str, str]:
    """Validate Buck2 overrides and select the fields for the current platform."""
    table = object_table(config.get(BUCK2, {}), f"[{BUCK2}] in {SETTINGS}")
    if extra := sorted(set(table) - {"platforms", "release", "repository"}):
        fail(f"[{BUCK2}] in {SETTINGS} has unsupported keys: {', '.join(extra)}")
    overrides: dict[str, str] = {}
    for key in ("repository", "release"):
        if key not in table:
            continue
        value = table[key]
        if not isinstance(value, str) or not value:
            fail(f"[{BUCK2}] {key} in {SETTINGS} must be a non-empty string")
        overrides[key] = value

    platforms = object_table(table.get("platforms", {}), f"[{BUCK2}.platforms] in {SETTINGS}")
    if extra := sorted(set(platforms) - set(PLATFORMS)):
        fail(f"[{BUCK2}.platforms] in {SETTINGS} has unsupported platforms: {', '.join(extra)}")
    for configured_platform, value in platforms.items():
        entry = object_table(value, f"[{BUCK2}.platforms.{configured_platform}] in {SETTINGS}")
        if extra := sorted(set(entry) - {"artifact", "sha256"}):
            fail(
                f"[{BUCK2}.platforms.{configured_platform}] in {SETTINGS} has unsupported keys: "
                f"{', '.join(extra)}"
            )
        for key in ("artifact", "sha256"):
            if key not in entry:
                continue
            item = entry[key]
            if not isinstance(item, str) or not item:
                fail(
                    f"[{BUCK2}.platforms.{configured_platform}] {key} in {SETTINGS} "
                    "must be a non-empty string"
                )
            if key == "sha256" and not is_hex(item, 64):
                fail(
                    f"[{BUCK2}.platforms.{configured_platform}] sha256 in {SETTINGS} "
                    "must be 64 lowercase hexadecimal characters"
                )
            if configured_platform == platform:
                overrides[key] = item
    return overrides


def _pinned_binary(
    pin: Mapping[str, str], tool: str, platform: str, source: str, *, compressed: bool, fetch: bool
) -> Path | None:
    """A pinned binary, fetched and verified the first time it is asked for.

    Cached by its own hash, so a bumped pin lands beside the old one and going back finds it there.
    Without `fetch`, None.
    """
    repository = pin.get("repository")
    release = pin.get("release")
    artifact = pin.get("artifact")
    sha256 = pin.get("sha256")
    if not (repository and release and artifact and sha256):
        fail(f"{source} pins no whole {tool} for {platform}")
    if not is_hex(sha256, 64):
        fail(f"the {tool} pinned for {platform} has no SHA-256 to verify against: {sha256!r}")

    cache = Path(os.environ.get("XDG_CACHE_HOME") or Path.home() / ".cache")
    binary = cache / "tine" / tool / sha256 / tool
    if binary.is_file():
        return binary
    if not fetch:
        return None
    url = f"https://github.com/{repository}/releases/download/{release}/{artifact}"
    return _download_binary(url, sha256, binary, compressed=compressed)


def buck2_binary(config: Mapping[str, object], cell: Path, *, fetch: bool = True) -> Path | None:
    """The pinned Buck2 binary. The pin is this cell's, overridable key by key in `[buck2]`."""
    platform = _host_platform()
    pin = declared_pin(cell, BUCK2, platform) | buck2_pin_overrides(config, platform)
    source = f"{cell / PINS} and [{BUCK2}] in {SETTINGS}"
    return _pinned_binary(pin, BUCK2, platform, source, compressed=True, fetch=fetch)


def mount_namespace_marker(digest: str) -> str:
    """Build the environment marker for a mount digest and namespace.

    Include the namespace to distinguish a marker inherited from the current build from a stale or
    manually exported value.
    """
    try:
        namespace = os.readlink("/proc/self/ns/mnt")
    except OSError:
        namespace = None
    return f"{digest} {namespace}"


def namespace_mount_targets(root: Path) -> list[str] | None:
    """Recover mounted targets without rereading mutable declarations or source paths."""
    value = os.environ.get(MARKER, "")
    digest = value.partition(" ")[0]
    if not is_hex(digest, 16) or value != mount_namespace_marker(digest):
        return None
    path = root / PRIVATE_CONFIG
    config = read_generated_buckconfig(path)
    if DAEMON_BUSTER not in config.get("buck2", {}):
        return None
    if config.get("buck2", {}).get(DAEMON_BUSTER) != BUSTER_PREFIX + digest:
        fail(f"{path}: does not match this invocation's mount namespace")
    return [target.strip() for target in config.get(SECTION, {}).get(DEV, "").split(",") if target.strip()]


def namespace_gitdirs(root: Path) -> dict[Path, str]:
    """Map mounted gitfile checkouts to their saved Git metadata directories."""
    import json

    path = root / PRIVATE_CONFIG
    value = read_generated_buckconfig(path).get(SECTION, {}).get(GITDIRS, "{}")
    try:
        gitdirs = string_table(json.loads(value), str(path))
        return {root / target: gitdir for target, gitdir in gitdirs.items()}
    except ValueError as error:
        fail(f"{path}: invalid private Git directories: {error}")


def create_mount_namespace(root: Path, mounts: dict[str, str]) -> str:
    """Keep the mount identity private while the project's ordinary config stays live."""
    import json

    private = root / PRIVATE_MOUNTS
    if resolved(private) != private:
        fail(f"{private}: the private config directory must not be a symlink")
    try:
        private.mkdir(parents=True, exist_ok=True)
    except OSError as error:
        fail(f"cannot prepare {private}: {error}")
    try:
        # Always create a user namespace, even with CAP_SYS_ADMIN, to scope mount authority to this
        # invocation. It must precede the mount namespace to grant a non-root caller mount permission.
        isolation.unprivileged_user_namespace(become_root=False)
        isolation.fix_user_namespace_capabilities(network=False)
        isolation.unshare(isolation.CLONE_NEWNS)
    except isolation.SandboxOSError as error:
        print(error.message, file=sys.stderr)
        fail("cannot create the mount namespace")
    except OSError as error:
        fail(f"cannot create the mount namespace: {error}")

    gitdirs: dict[str, str] = {}
    for target, source in mounts.items():
        # Git resolves relative gitfile pointers against the original checkout, not its bind target.
        # Ordinary .git directories stay accessible through the mount and need no extra state.
        if (Path(source) / ".git").is_file():
            gitdirs[target] = _git("rev-parse", "--absolute-git-dir", directory=Path(source))
        try:
            isolation.mount(Path(source), root / target, flags=isolation.MS_BIND | isolation.MS_REC)
        except OSError as error:
            fail(f"mount {target}: cannot build it from {source}: {error}")

    digest = mount_digest(root, mounts)
    # Buck reads startup settings from every root-cell config layer, but does not follow includes
    # or apply command-line overrides there. A private fragment prevents another client from
    # relabelling these mounts between our setup and Buck's first config read.
    content = "\n".join(
        [
            BLOCK_BEGIN,
            "[buck2]",
            f"{DAEMON_BUSTER} = {BUSTER_PREFIX}{digest}",
            f"[{SECTION}]",
            f"{DEV} = {', '.join(sorted(mounts))}",
            *([f"{GITDIRS} = {json.dumps(gitdirs, sort_keys=True)}"] if gitdirs else []),
            BLOCK_END,
            "",
        ]
    )
    try:
        isolation.mount(Path("tmpfs"), private, "tmpfs", options="mode=0755")
        (root / PRIVATE_CONFIG).write_text(content)
    except OSError as error:
        fail(f"cannot prepare the private mount config: {error}")
    return digest


def cells_of(config: dict[str, dict[str, str]]) -> dict[str, str]:
    """Buck2 reads either spelling and keeps the older one working."""
    return config["cells"] if "cells" in config else config.get("repositories", {})


def configured_mount_targets(root: Path) -> set[str]:
    """Existing project directories registered as cell roots."""
    targets: set[str] = set()
    config = read_project_buckconfig(root, buckconfig_overrides(project_settings(root), root / CONFIG))
    for value in cells_of(config).values():
        path = Path(value)
        if (
            path == Path()
            or path.is_absolute()
            or ".." in path.parts
            or any(path.is_relative_to(reserved) for reserved in (HOME, ".buckconfig.d"))
        ):
            continue
        target = path.as_posix()
        if (root / target).is_dir() and resolved(root / target) == root / target:
            targets.add(target)
    return targets


def graph_mount_targets(root: Path) -> set[str]:
    """Query checkout slots from the project's root cell."""
    import subprocess

    query = f"attrfilter(labels, '{MOUNT_TARGET_LABEL}', //...)"
    # The child changes to the project root, so its entry point needs an absolute name.
    command = [
        str(COMMAND_PATH.absolute()),
        "buck",
        "-v",
        "0",
        "uquery",
        query,
    ]
    try:
        proc = subprocess.run(command, cwd=root, stdout=subprocess.PIPE, text=True)
    except OSError as error:
        fail(f"cannot query mount targets: {error}")
    if proc.returncode != 0:
        raise SystemExit(proc.returncode)

    targets: set[str] = set()
    for label in proc.stdout.splitlines():
        package, separator, name = label.rpartition(":")
        cell, root_separator, path = package.partition("//")
        if not separator or not root_separator or not cell or not name:
            fail(f"buck returned an invalid mount target: {label!r}")
        target = (Path(path) / name.removesuffix(".git")).as_posix()
        targets.add(target)
    return targets


def mount_targets(root: Path) -> set[str]:
    """Every target that may be overridden by a local mount."""
    return configured_mount_targets(root) | graph_mount_targets(root)


def configured_wrapper_entrypoint(root: Path, config: dict[str, dict[str, str]]) -> Path:
    """Keep the wrapper, rules and Buck2 pin in the configured tine checkout."""
    cell = cells_of(config).get(CELL)
    if cell is None:
        return COMMAND_PATH.absolute()
    command = root / cell / COMMAND
    if not command.is_file():
        fail(f"{root / cell}: {CELL} cell has no {COMMAND}")
    return command


def reexec_configured_wrapper(
    root: Path, config: dict[str, dict[str, str]], mounts: dict[str, str], argv: list[str]
) -> None:
    """Hand over to the configured wrapper after entering any new mounts.

    Mounting can replace this checkout without changing its path, so always reload after mounting.
    Otherwise resolve symlinks like the launcher does to avoid handing over to ourselves.
    """
    environment = dict(os.environ)
    if mounts:
        working = cwd()
        digest = create_mount_namespace(root, mounts)
        environment[MARKER] = mount_namespace_marker(digest)
        try:
            os.chdir(working)
        except OSError as error:
            fail(f"cannot return to {working}: {error}")
    command = configured_wrapper_entrypoint(root, config)
    if not mounts and command.resolve() == COMMAND_PATH.resolve():
        return

    try:
        os.execve(command, [str(command), *argv], environment)
    except OSError as error:
        fail(f"cannot run {command}: {error}")


VERBS = {
    "buck": "run the pinned Buck2, which every other command configures",
    "box": "run the project's root box target",
    "mount": "manage external directories mounted over project paths",
    "init": "write the configuration a project needs to build against a checkout of the tine cell",
    "completion": "print the completion script for bash, fish or zsh",
}
HELP = ("-h", "--help", "help")
PROJECT_COMMAND_DESCRIPTION = "run a configured project command"


@dataclass(frozen=True, slots=True)
class ProjectCommand:
    """A validated project command.

    The body is either a shell script or a non-empty tuple of Buck argument vectors. Validation ensures
    every vector starts with ``buck``.
    """

    description: str
    body: str | tuple[tuple[str, ...], ...]
    cwd: Path | None = None


def validate_command_name(name: str, source: str) -> None:
    """Require one safe command and completion-script word."""
    if (
        not name
        or name.startswith("-")
        or not all(c.isascii() and (c.isalnum() or c in "._-") for c in name)
    ):
        fail(f"[commands] in {source} has invalid command name {name!r}")

    if name in VERBS or name in HELP:
        fail(f"[commands] in {source} uses reserved command name {name!r}")


def validate_commands(value: object, source: str = SETTINGS) -> dict[str, ProjectCommand]:
    """Validate and normalize the structured project command table."""
    table = object_table(value, f"[{COMMANDS}] in {source}")
    commands: dict[str, ProjectCommand] = {}
    for name, value in table.items():
        validate_command_name(name, source)

        definition = object_table(value, f"[{COMMANDS}.{name}] in {source}")
        if extra := sorted(set(definition) - {"cwd", "description", "script", "steps"}):
            fail(f"[{COMMANDS}.{name}] in {source} has unsupported keys: {', '.join(extra)}")

        description = definition.get("description", PROJECT_COMMAND_DESCRIPTION)
        if not isinstance(description, str) or not description.strip() or not description.isprintable():
            fail(f"[{COMMANDS}.{name}] description in {source} must be a non-empty printable string")

        if ("steps" in definition) == ("script" in definition):
            fail(f"[{COMMANDS}.{name}] in {source} must define exactly one of steps or script")

        command_cwd = None
        if "cwd" in definition:
            raw_cwd = definition["cwd"]
            if not isinstance(raw_cwd, str) or not raw_cwd or "\0" in raw_cwd or Path(raw_cwd).is_absolute():
                fail(f"[{COMMANDS}.{name}] cwd in {source} must be a non-empty relative path")
            command_cwd = Path(raw_cwd)

        if "script" in definition:
            script = definition["script"]
            if not isinstance(script, str) or not script.strip():
                fail(f"[{COMMANDS}.{name}] script in {source} must be a non-empty string")
            if "\0" in script:
                fail(f"[{COMMANDS}.{name}] script in {source} must not contain NUL")
            commands[name] = ProjectCommand(description, script, command_cwd)
            continue

        raw_steps = definition["steps"]
        if not isinstance(raw_steps, list) or not raw_steps:
            fail(f"[{COMMANDS}.{name}] steps in {source} must be a non-empty array")

        steps: list[tuple[str, ...]] = []
        for number, raw_step in enumerate(raw_steps, start=1):
            if not isinstance(raw_step, list) or not raw_step:
                fail(f"[{COMMANDS}.{name}] step {number} in {source} must be a non-empty array")

            if any(not isinstance(argument, str) for argument in raw_step):
                fail(f"[{COMMANDS}.{name}] step {number} in {source} must contain only strings")

            step = tuple(cast(list[str], raw_step))
            if any("\0" in argument for argument in step):
                fail(f"[{COMMANDS}.{name}] step {number} in {source} must not contain NUL")
            if step[0] != "buck":
                fail(f"[{COMMANDS}.{name}] step {number} in {source} must start with buck, not {step[0]}")

            steps.append(step)

        commands[name] = ProjectCommand(description, tuple(steps), command_cwd)

    return commands


def project_commands(directory: Path) -> tuple[Path, dict[str, ProjectCommand]] | None:
    """Read the root and commands for the project containing directory, if one exists."""
    try:
        root = project_root(directory)
    except SystemExit:
        return None
    return root, validate_commands(project_settings(root).get(COMMANDS, {}))


def command_descriptions(configured: dict[str, ProjectCommand]) -> dict[str, str]:
    """Built-in commands followed by validated project commands."""
    return VERBS | {name: configured[name].description for name in sorted(configured)}


def run_step(argv: list[str]) -> int:
    """Run an intermediate step while keeping signals attached to its child."""
    import subprocess

    with subprocess.Popen(argv) as process, ExitStack() as cleanup:
        forwarded = None

        def forward(number: int, _frame: object) -> None:
            nonlocal forwarded
            forwarded = number
            try:
                process.send_signal(number)
            except ProcessLookupError:
                pass

        for number in (signal.SIGHUP, signal.SIGTERM):
            previous = signal.signal(number, forward)
            cleanup.callback(signal.signal, number, previous)
        try:
            returncode = process.wait()
        except KeyboardInterrupt:
            forward(signal.SIGINT, None)
            returncode = process.wait()
        return -forwarded if forwarded is not None else returncode


def run_project_command(
    root: Path,
    name: str,
    command: ProjectCommand,
    arguments: list[str],
) -> None:
    """Run a script or each Buck step, passing caller arguments to the final process."""
    executable = str(COMMAND_PATH.absolute())
    if command.cwd is not None:
        directory = root / command.cwd
        try:
            os.chdir(directory)
        except OSError as error:
            fail(f"cannot run command {name} from {directory}: {error}")

    if isinstance(command.body, str):
        argv = ["sh", "-c", command.body, name, *arguments]
        try:
            os.execvp(argv[0], argv)
        except OSError as error:
            fail(f"cannot run command {name}: {error}")
        return

    steps = command.body
    for number, step in enumerate(steps[:-1], start=1):
        argv = [executable, *step]
        try:
            returncode = run_step(argv)
        except OSError as error:
            fail(f"cannot run command {name} step {number}: {error}")
        if returncode != 0:
            raise SystemExit(returncode if returncode > 0 else 128 - returncode)
    argv = [executable, *steps[-1], *arguments]
    try:
        os.execv(executable, argv)
    except OSError as error:
        fail(f"cannot run command {name} step {len(steps)}: {error}")


def _replace_completion_fragment(script: str, old: str, new: str) -> str:
    """Replace what Buck2's completion script says, rather than emit one that completes nothing."""
    if old not in script:
        fail(f"buck2's completion script has no {old!r} to rewrite; the pin moved under it")
    return script.replace(old, new)


def _buck2_completion_script(binary: Path, shell: str) -> str:
    import subprocess

    try:
        proc = subprocess.run([binary, "completion", shell], stdout=subprocess.PIPE, text=True)
    except OSError as error:
        fail(f"cannot run {binary}: {error}")
    if proc.returncode != 0:
        raise SystemExit(proc.returncode)
    return proc.stdout


def rewrite_completion_script(
    script: str, shell: str, configured: dict[str, ProjectCommand] | None = None
) -> str:
    """Buck2's own completion script, rewritten to complete `tine buck` instead.

    Its arguments arrive one word further along than the script expects, so the helper that finds
    the subcommand skips that word and the rest follows. Rewritten rather than wrapped because the
    dynamic half runs `buck2 complete` from inside the shell functions, which would resolve to
    whatever `buck2` is on PATH, or to nothing at all.
    """
    script = re.sub(
        r"^# @generated by .*$",
        f"# @generated by `tine completion {shell}`",
        script,
        count=1,
        flags=re.M,
    )
    available = command_descriptions(configured or {})
    if shell == "fish":
        return _rewrite_fish_completion(script, available)
    # bash and zsh spell buck2 into function names, the subcommand state machine and the
    # registration alike, so rename wholesale; a few help strings now say tine where they mean Buck2.
    script = script.replace("buck2", "tine")
    # All but the entry point: `_tine` is the name a shell autoloads this file under, and has to be
    # the completer that knows this command's own verbs, with Buck2's reached through it.
    script = re.sub(r"\b_tine\b", "_tine_buck2", script)
    # An array, the command it names now being two words; the hook itself is Buck2's own.
    script = _replace_completion_fragment(
        script,
        '_BUCK_COMPLETE_BIN="${_BUCK_COMPLETE_BIN:-tine}"',
        "[[ -n ${_BUCK_COMPLETE_BIN[*]} ]] || _BUCK_COMPLETE_BIN=(tine buck)",
    )
    if shell == "bash":
        # Buck2 registers its completers for the `buck` command too, which this one is not.
        script = re.sub(r"^[ \t]*complete -F .* buck\n", "", script, flags=re.M)
        own = _BASH.replace(VERBS_MARKER, " ".join(available))
    else:
        # A shell reads the commands a file completes off its first line, and `buck` there would
        # bind a real buck2 installation's completion to this script.
        script = _replace_completion_fragment(script, "#compdef tine buck", "#compdef tine")
        script = _replace_completion_fragment(script, "\ncompdef __tine_fix buck tine\n", "\n")
        # Paired with that registration, and this file registers itself at the end instead.
        script = _replace_completion_fragment(script, "\ncompdef -d tine\n", "\n")
        # Buck2's entry point runs where it sits, which is before the completer that dispatches into
        # it is defined; the same idiom goes to the end of the file instead.
        script = _replace_completion_fragment(
            script,
            '\nif [ "$funcstack[1]" = "_tine_buck2" ]; then\n    _tine_buck2 "$@"\n'
            "else\n    compdef _tine_buck2 tine\nfi\n",
            "\n",
        )
        described = "\n".join(
            f"        {quote_zsh_completion_entry(name, description)}"
            for name, description in available.items()
        )
        own = _ZSH.replace(VERBS_MARKER, described)
    return script + own


def quote_fish_description(text: str) -> str:
    """What fish reads back as `text` inside the single quotes a description is written in."""
    return text.replace("\\", "\\\\").replace("'", "\\'")


def quote_zsh_completion_entry(name: str, description: str) -> str:
    """Quote one `_describe` entry as a zsh array word."""
    description = description.replace("\\", "\\\\").replace(":", "\\:")
    return "'" + f"{name}:{description}".replace("'", "'\\''") + "'"


def _rewrite_fish_completion(script: str, available: dict[str, str]) -> str:
    script = re.sub(r"^complete -c buck2 ", "complete -c tine ", script, flags=re.M)
    script = script.replace("__fish_buck2", "__fish_tine").replace("__buck2", "__tine")
    script = re.sub(r"^complete -c buck -w buck2\n", "", script, flags=re.M)

    # Everything clap generated hangs off this one helper, so shifting it past `buck` shifts the lot.
    script = _replace_completion_fragment(
        script,
        """    set -l cmd (commandline -opc)
    set -e cmd[1]
    argparse -s (__fish_tine_global_optspecs)""",
        """    set -l cmd (commandline -opc)
    set -e cmd[1]
    # Buck2's arguments start after `tine buck`, and belong to nothing else.
    test "$cmd[1]" = buck
    or return 1
    set -e cmd[1]
    argparse -s (__fish_tine_global_optspecs)""",
    )
    # The hand-written half tokenizes the line itself, so it needs the same word skipped.
    script = _replace_completion_fragment(
        script,
        """    set -l subcommand (__tine_subcommand $cmd)""",
        """    test "$cmd[2]" = buck
    or return 1
    set -l subcommand (__tine_subcommand $cmd[2..])""",
    )
    script = _replace_completion_fragment(
        script, '    buck2 complete --target="$cur"', '    tine buck complete --target="$cur"'
    )
    verbs = "\n".join(
        f"complete -c tine -n __fish_use_subcommand -f -a {verb} -d '{quote_fish_description(description)}'"
        for verb, description in available.items()
    )
    return script + _FISH.replace(VERBS_MARKER, verbs)



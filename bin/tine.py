def buckconfig_overrides(settings: dict[str, dict[str, object]], source: Path) -> dict[str, dict[str, str]]:
    """Validate explicit Buck settings, requiring strings as Buck's configuration does."""
    table = object_table(settings.get(BUCKCONFIG, {}), f"[{BUCKCONFIG}] in {source}")
    config: dict[str, dict[str, str]] = {}
    for section, values in table.items():
        description = f"[{BUCKCONFIG}.{section}] in {source}"
        if not re.fullmatch(r"[\w.-]+", section):
            fail(f"{description} has an invalid section name")
        config[section] = string_table(values, description)
        for key, value in config[section].items():
            if not re.fullmatch(r"[\w.-]+", key) or not buckconfig_value_round_trips(value) or "\0" in value:
                fail(f"{description} {key!r} cannot be written to .buckconfig as it stands")
    return config


def validate_mount_config(config: dict[str, dict[str, str]]) -> None:
    """Keep higher-precedence project settings from overriding the private mount identity."""
    for section, key in (("buck2", DAEMON_BUSTER), (SECTION, DEV)):
        if key in config.get(section, {}):
            fail(f"[{section}] {key} is reserved while mounts are declared")


def render_project_buckconfig(source: Path, overrides: dict[str, dict[str, str]]) -> str:
    """Generate consuming-project defaults with explicit project overrides."""
    # The defaults are required; parse_buckconfig intentionally tolerates absent config layers.
    config: dict[str, dict[str, str]] = {}
    _parse_buckconfig_lines(
        _logical_buckconfig_lines(_split_generated_block(source, must_exist=True)[0]),
        config,
        "",
        source.parent,
    )
    cells_of(config).pop(CELL, None)
    config.setdefault("cells", {}).setdefault("root", ".")
    config.setdefault("parser", {})[DETECTOR] = (
        f"target:root//...->{DEFAULT_PLATFORM} target:{CELL}//...->{DEFAULT_PLATFORM}"
    )
    for section, values in overrides.items():
        config.setdefault(section, {}).update(values)
    lines = [CONFIG_HEADER]
    for section, values in config.items():
        if values:
            lines += [
                "",
                *([f"[{section}]"] if section else []),
                *(f"{key} = {value}" for key, value in values.items()),
            ]
    return "\n".join(lines) + "\n"


def refresh_project_buckconfig(root: Path, overrides: dict[str, dict[str, str]]) -> None:
    """Refresh generated defaults from the visible checkout, leaving standalone configs alone."""
    # Local cell overrides must select the same defaults as the wrapper handover.
    cell = cells_of(read_project_buckconfig(root, overrides)).get(CELL)
    if cell is None or root / cell == root:
        if overrides:
            fail(f"{root / CONFIG}: set standalone Buck overrides in .buckconfig instead")
        return
    if CELL not in cells_of(overrides):
        # Without a TOML cell declaration, the bootstrap still owns the project cell registrations.
        cells = cells_of(parse_buckconfig(root / ".buckconfig")) | cells_of(overrides)
        overrides = overrides | {"cells": cells}
    write_if_changed(root / ".buckconfig", render_project_buckconfig(root / cell / ".buckconfig", overrides))


@contextmanager
def mount_table_lock(root: Path) -> Iterator[None]:
    """Keep concurrent mount-table edits from losing each other's changes."""
    path = root / MOUNT_LOCK
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        handle = path.open("a")
    except OSError as error:
        fail(f"cannot prepare {path} for locking: {error}")
    with handle:
        try:
            # Only contention is retryable; failures from either flock must reach the outer handler.
            try:
                fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                print("tine: waiting for another mount update to finish", file=sys.stderr)
                fcntl.flock(handle, fcntl.LOCK_EX)
        except OSError as error:
            fail(f"cannot lock {path}: {error}")
        except KeyboardInterrupt:
            fail("mount update interrupted")
        yield


def update_git_excludes(directory: Path, entries: str) -> None:
    """Keep what a build leaves behind out of git's way where `.gitignore` is not ours to write.

    `.git/info/exclude` is committed nowhere, so a project that has a `.gitignore` of its own gets
    what this would have said without this command editing a file it owns.
    """
    header = "# @generated by `tine init`; what a build leaves behind."
    try:
        common = _git("rev-parse", "--git-common-dir", directory=directory)
    except SystemExit:
        return
    # Relative to the directory it was asked in, except where it is not; either way a worktree and
    # a submodule both name the one directory this belongs in.
    path = directory / common / "info" / "exclude"
    lines = read_lines(path) if path.is_file() else []
    if not (missing := [entry for entry in entries.split("\n") if entry and entry not in lines]):
        return
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
    except OSError as error:
        fail(f"cannot create {path.parent}: {error}")
    write_if_changed(path, "\n".join([*lines, *([] if header in lines else [header]), *missing]) + "\n")
    print(f"tine: excluded {', '.join(missing)} in {path}", file=sys.stderr)


def init_command(directory: Path, arguments: list[str]) -> None:
    """Write the configuration a project needs to build against a checkout of this cell.

    Shadows Buck2's own `init`, which writes an empty prelude project rather than this cell.
    """
    import argparse
    import json

    parser = argparse.ArgumentParser(prog="tine init", description="write the configuration a project needs")
    parser.add_argument(
        "cell",
        nargs="?",
        metavar="<path>",
        help="a checkout of this cell in the project, a submodule of it or any other directory"
        " (default: the checkout this command is part of)",
    )
    args = parser.parse_args(arguments)
    if (directory / ".buckconfig").exists():
        fail(f"{directory / '.buckconfig'} already exists")

    # Against the project rather than the working directory, which differ where a path was passed.
    checkout = (directory / Path(args.cell).expanduser()).absolute() if args.cell else wrapper_cell_root()
    try:
        path = checkout.relative_to(directory.absolute())
    except ValueError:
        fail(f"{checkout} is not in {directory}, so it cannot be a cell of this project")
    if not (checkout / PINS).is_file():
        fail(f"{checkout} is no checkout of the {CELL} cell: it has no {PINS}")
    if not buckconfig_value_round_trips(str(path)):
        fail(f"{path} cannot be written to .buckconfig as it stands")

    overrides = buckconfig_overrides(project_settings(directory), directory / CONFIG)
    settings = directory / CONFIG
    if "cells" in overrides:
        if overrides["cells"].get(CELL) != str(path):
            fail(f"[{BUCKCONFIG}.cells] in {settings} must set {CELL} to {str(path)!r}")
    else:
        content = "\n".join(read_lines(settings)) + "\n\n" if settings.exists() else ""
        content += (
            f'[{BUCKCONFIG}.cells]\nroot = "."\n{CELL} = {json.dumps(str(path), ensure_ascii=False)}\n'
        )
        try:
            tomllib.loads(content)
        except tomllib.TOMLDecodeError as error:
            fail(f"cannot add [{BUCKCONFIG}.cells] to {settings}: {error}")
        write_if_changed(settings, content)
        print(f"tine: wrote {CONFIG}", file=sys.stderr)
        overrides["cells"] = {"root": ".", CELL: str(path)}

    # `.buckconfig` last: it is what a second run refuses to overwrite, so nothing that can fail
    # should come after it.
    if (directory / ".gitignore").exists():
        print("tine: .gitignore exists, left alone", file=sys.stderr)
        update_git_excludes(directory, GITIGNORE)
    else:
        write_if_changed(directory / ".gitignore", GITIGNORE)
        print("tine: wrote .gitignore", file=sys.stderr)
    write_if_changed(
        directory / ".buckconfig", render_project_buckconfig(checkout / ".buckconfig", overrides)
    )
    print("tine: wrote .buckconfig", file=sys.stderr)


def mount_command(root: Path, arguments: list[str]) -> None:
    """Manage project paths backed by directories outside the project.

    Mount declarations are machine-local and remain outside the namespace they configure.
    """
    import argparse

    parser = argparse.ArgumentParser(
        prog="tine mount", description="manage external directories mounted over project paths"
    )
    verbs = parser.add_subparsers(dest="verb", metavar="<verb>", required=True)
    add = verbs.add_parser("add", help="mount an external directory over a project path")
    add.add_argument("target", help="project path to mount over")
    add.add_argument("source", help="external directory to mount")
    remove = verbs.add_parser("remove", help="remove a mount declaration")
    remove.add_argument("target", help="the path to stop mounting over")
    verbs.add_parser("list", help="print mount targets and their current sources")
    args = parser.parse_args(arguments)

    if args.verb == "list":
        declared = local_mounts(root)
        targets = mount_targets(root)
        targets.update(declared)
        names = sorted(targets)
        width = max([len("TARGET"), *(len(target) for target in names)])
        print(f"{'TARGET':<{width}} SOURCE")
        for target in names:
            print(f"{target:<{width}} {declared.get(target, 'default')}")
        if not names:
            print("tine: no mount targets", file=sys.stderr)
        return

    target = relative_mount_target(root, resolve_mount_target(Path(args.target)))
    source = None
    if args.verb == "add":
        source = resolved(Path(args.source))
        # Validate before writing so this command cannot create an unusable declaration.
        validate_mount_declaration(root, target, str(source), allow_missing_target=True)

    with mount_table_lock(root):
        declared = local_mounts(root)
        if args.verb == "remove":
            if declared.pop(target, None) is None:
                fail(f"{target} is not mounted")
            message = f"{target} is no longer mounted"
        else:
            assert source is not None
            # Repairing an existing declaration must not need a graph query using its missing source.
            if (
                target not in declared
                and target not in configured_mount_targets(root)
                and target not in graph_mount_targets(root)
            ):
                fail(f"mount {target}: not a valid target; `tine mount list` lists valid targets")
            validate_mount_config(
                read_project_buckconfig(root, buckconfig_overrides(project_settings(root), root / CONFIG))
            )
            for other in declared:
                if target != other and mount_targets_overlap(target, other):
                    fail(f"mount {target}: overlaps mount {other}")
            if not (root / target).exists():
                try:
                    (root / target).mkdir()
                except OSError as error:
                    fail(f"mount {target}: cannot create its directory: {error}")
            validate_mount_declaration(root, target, str(source))
            declared[target] = str(source)
            message = f"{target} is built from {source}"
        # Preserve other entries without validation so a stale declaration can still be removed.
        update_git_excludes(root, GITIGNORE)
        write_mounts(root, declared)
        print(f"tine: {message}", file=sys.stderr)


@dataclass(frozen=True, slots=True)
class BuckCommand:
    subcommand: str | None
    isolation: str | None


def parse_buck_command(argv: list[str]) -> BuckCommand:
    """Parse a buck argument vector."""
    subcommand: str | None = None
    isolation: str | None = None
    rest = argv
    while rest:
        word = rest[0]
        if word == "--":
            break
        if word == FLAG_ISOLATION and len(rest) > 1:
            isolation = rest[1]
        elif word.startswith(f"{FLAG_ISOLATION}="):
            isolation = word.removeprefix(f"{FLAG_ISOLATION}=")
        elif not word.startswith("-") and subcommand is None:
            subcommand = word
        rest = rest[2:] if word in VALUE_FLAGS else rest[1:]
    return BuckCommand(subcommand=subcommand, isolation=isolation)


def glob_literal(value: str) -> str:
    """Escape a path embedded in a Buck project-ignore glob."""
    return "".join("\\" + char if char in "\\*?{[" else char for char in value)


def collect_project_ignores(
    root: Path,
    config: dict[str, dict[str, str]],
    mounts: list[str],
    gitdirs: Mapping[Path, str],
) -> list[str]:
    """The project ignores, including Git-ignored paths and mounted checkouts' build files.

    glob() stops at an upstream BUCK file before applying its exclusions. Buck applies project
    ignores earlier, so ignoring those build files lets the owning package's glob traverse the
    checkout. Resolve checkout-local ignores through Git so generated trees are hidden before Buck tries
    to read names it cannot represent.
    """
    if PROJECT_IGNORE in parse_buckconfig(root / LOCAL).get("project", {}):
        fail(
            f"{LOCAL}: [project] {PROJECT_IGNORE} would replace the generated ignores; "
            f"set it in .buckconfig or [{BUCKCONFIG}.project] in {CONFIG}"
        )
    patterns = [entry.strip() for entry in config.get("project", {}).get(PROJECT_IGNORE, "").split(",")]
    # Git's ignored-path listing does not include VCS metadata.
    patterns = [entry for entry in patterns if entry] + list(VCS_IGNORES)
    # Local build definitions may be kept out of Git. Exempt them in Git's query, as --directory can
    # otherwise collapse a directory containing only ignored build files before we see its contents.
    patterns += [
        glob_literal(path)
        for path in git_ignored_paths(root, gitdir=gitdirs.get(root), excludes=("!BUCK", "!BUCK.v2"))
    ]

    cell_roots = [Path(value) for value in cells_of(config).values()]
    for target in sorted(mounts):
        target_path = Path(target)
        # A cell mount must retain its own build files. A graph-declared checkout is the only other
        # kind of mount, including one nested inside a cell.
        if any(cell == target_path or cell.is_relative_to(target_path) for cell in cell_roots):
            continue
        literal = glob_literal(target)
        patterns += [f"{literal}/{name}" for name in ("BUCK", "**/BUCK")]
        patterns += [
            f"{literal}/{glob_literal(path)}"
            for path in git_ignored_paths(root / target, gitdir=gitdirs.get(root / target))
        ]
    return list(dict.fromkeys(patterns))


def prepare_buck(
    root: Path, settings: dict[str, dict[str, object]], argv: list[str], *, refresh_config: bool = True
) -> tuple[dict[str, dict[str, str]], list[str]]:
    """Select mounts and the wrapper before refreshing defaults from its checkout."""
    mounts = namespace_mount_targets(root)
    nested = bool(os.environ.get("BUCK2_BINARY"))
    overrides = buckconfig_overrides(settings, root / CONFIG)
    declared = declared_mounts(root) if mounts is None and not nested else {}
    reexec_configured_wrapper(root, read_project_buckconfig(root, overrides), declared, argv)
    if refresh_config and not nested:
        refresh_project_buckconfig(root, overrides)
    config = read_project_buckconfig(root)
    if mounts:
        validate_mount_config(config)
    return config, mounts or []


def buck_command(argv: list[str]) -> None:
    root = project_root(cwd())
    ensure_home(root)
    settings = project_settings(root)
    command = parse_buck_command(argv)
    # A completing shell must neither download nor rewrite shared configuration on a keypress.
    config, mounts = prepare_buck(
        root, settings, ["buck", *argv], refresh_config=command.subcommand != "complete"
    )
    # Hand over first so wrapper_cell_root() reads the configured checkout's pin.
    binary = buck2_binary(settings, wrapper_cell_root(), fetch=command.subcommand != "complete")
    if binary is None:
        return
    if command.subcommand != "complete" and not os.environ.get("BUCK2_BINARY"):
        gitdirs = namespace_gitdirs(root) if mounts else {}
        refresh_local_buckconfig(root, collect_project_ignores(root, config, mounts, gitdirs))
        if (cell := cells_of(config).get(CELL)) is not None and (checkout := root / cell) != root:
            # Buck resolves ignores within each cell, including in the daemon's file watcher.
            refresh_local_buckconfig(
                checkout,
                collect_project_ignores(checkout, read_project_buckconfig(checkout), [], gitdirs),
            )
    # BUCK2_BINARY lets a tool nest a Buck2 command without refreshing config under its build.
    environment = {"BUCK2_ARG0": "tine buck", "BUCK2_BINARY": str(binary)}
    try:
        os.execve(binary, [str(binary), *argv], os.environ | environment)
    except OSError as error:
        fail(f"cannot run {binary}: {error}")


def completion_command(arguments: list[str]) -> None:
    """Print the pinned Buck completion script in the configured namespace."""
    if len(arguments) != 1 or arguments[0] not in SHELLS:
        fail(f"completion takes one of {', '.join(SHELLS)}")
    try:
        root = project_root(cwd())
    except SystemExit as error:
        reason = str(error).removeprefix("tine: ")
        fail(f"{reason}; the script comes out of the Buck2 a project pins")
    ensure_home(root)
    settings = project_settings(root)
    prepare_buck(root, settings, ["completion", *arguments], refresh_config=False)
    configured = validate_commands(settings.get(COMMANDS, {}), str(root / CONFIG))
    binary = buck2_binary(settings, wrapper_cell_root())
    assert binary is not None
    print(
        rewrite_completion_script(_buck2_completion_script(binary, arguments[0]), arguments[0], configured),
        end="",
    )


def usage(configured: dict[str, ProjectCommand]) -> str:
    available = command_descriptions(configured)
    width = max(12, *(len(name) + 2 for name in available))
    return "usage: tine <command> [arguments]\n\n" + "".join(
        f"    {name:<{width}}{description}\n" for name, description in available.items()
    )


USAGE = usage({})


def main(argv: list[str]) -> None:
    """Dispatch on the first word, which `tine buck` needs and argparse would get in the way of.

    Everything after `buck` is Buck2's, including words that look like this command's options.
    """
    # Python turns a closed stdout into an exception; a command piped into `head` should not.
    signal.signal(signal.SIGPIPE, signal.SIG_DFL)
    name, rest = (argv[0], argv[1:]) if argv else (None, [])
    project: tuple[Path, dict[str, ProjectCommand]] | None = None
    configured: dict[str, ProjectCommand] = {}
    if name is None or name in HELP or name not in VERBS:
        project = project_commands(cwd())
        if project is not None:
            _, configured = project

    if name == "buck":
        buck_command(rest)
    elif name == "box":
        buck_command(["-v", "0", "run", "//:box", *rest])
    elif name == "mount":
        mount_command(project_root(cwd()), rest)
    elif name == "init":
        # Before the project root is resolved, because writing one is what this is for.
        init_command(cwd(), rest)
    elif name == "completion":
        completion_command(rest)
    elif name in (*HELP, None):
        print(usage(configured), end="")
    elif project is not None and name in configured:
        root, _ = project
        run_project_command(root, name, configured[name], rest)
    else:
        fail(f"no such command: {name}\n{usage(configured)}")


if __name__ == "__main__":
    main(sys.argv[1:])
